// Fallback generator for remaining hexagrams so every combination works seamlessly
export function getHexagramData(upperKey, lowerKey) {
  const trigramCodes = {
    "乾": "111", "兌": "011", "離": "101", "震": "001",
    "巽": "110", "坎": "010", "艮": "100", "坤": "000"
  };
  const upCode = trigramCodes[upperKey] || "111";
  const lowCode = trigramCodes[lowerKey] || "111";
  // Hexagram lines from bottom to top: lower 3 lines then upper 3 lines
  const key = `${lowCode}${upCode}`;

  if (HEXAGRAMS[key]) {
    return HEXAGRAMS[key];
  }

  // Generic balanced synthesis for unlisted hexagrams
  const up = Object.values(TRIGRAMS).find((t) => t.name === upperKey) || TRIGRAMS[1];
  const low = Object.values(TRIGRAMS).find((t) => t.name === lowerKey) || TRIGRAMS[1];
  const fullName = upperKey === lowerKey ? `${upperKey}為${up.symbol}` : `${up.symbol}${low.symbol}${upperKey}`;

  return {
    number: 0,
    name: fullName,
    upper: upperKey,
    lower: lowerKey,
    judgment: "亨，利貞。",
    image: `${up.symbol}在${low.symbol}上，君子以順天應時，謹厚修德。`,
    overview: `上卦為${up.name}（${up.symbol}，象徵${up.nature}），下卦為${low.name}（${low.symbol}，象徵${low.nature}）。外在呈現${up.nature}之勢，內在蘊含${low.nature}之基。`,
    advice: `外順${up.nature}、內守${low.nature}，審時度勢，因勢利導，自得吉慶。`,
    lineTexts: [
      "初爻：起步伊始，宜靜觀其變，審慎奠定基石。",
      "二爻：居中得位，適度展現實力，善結善緣。",
      "三爻：內外交接之際，處事需更為周全謹慎。",
      "四爻：進一步入上層，宜順應時勢與上層步調一致。",
      "五爻：主位尊崇，以中正寬和之德凝聚整體共識。",
      "上爻：物極將反，居高思危，適可而止方保長久。"
    ]
  };
}
